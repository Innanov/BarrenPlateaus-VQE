"""
    visualize_all_ansatz_circuits(analyzer; output_dir::String="./ansatz_circuits", file_format::String="pdf")

Generate circuit visualizations for all VQE methods.
"""
function visualize_all_ansatz_circuits(analyzer; 
                                      output_dir::String="./ansatz_circuits", 
                                      file_format::String="pdf")
    
    # Create output directory
    mkpath(output_dir)
    
    println("🎨 Creating VQE ansatz circuit visualizations...")
    println("   📁 Output directory: $output_dir")
    println("   📄 Format: $file_format")
    
    # Get system info
    n_qubits = analyzer.molecular_system.n_qubits
    molecule_name = analyzer.molecular_system.name
    
    # VQE methods to visualize
    vqe_methods = ["StandardVQE", "SEAVQE", "LocalGlobalVQE", "AdiabaticVQE", "PretrainedVQE"]
    
    circuit_infos = CircuitInfo[]
    saved_files = String[]
    
    println("   🔍 Processing $(length(vqe_methods)) VQE methods for $molecule_name ($(n_qubits) qubits)")
    
    for method_name in vqe_methods
        println("   🔧 Processing $method_name...")
        
        # Try to extract circuit from VQE method directly
        circuit_info = extract_circuit_from_vqe_method(method_name, n_qubits)
        
        # Fallback: try to extract from analyzer results if available
        if circuit_info === nothing && haskey(analyzer.results, method_name)
            circuit_info = extract_circuit_from_analyzer_results(method_name, analyzer.results[method_name])
        end
        
        if circuit_info !== nothing
            push!(circuit_infos, circuit_info)
            
            # Create circuit visualization
            circuit_filename = "ansatz_$(method_name).svg"
            circuit_path = joinpath(output_dir, circuit_filename)
            
            if create_circuit_plot(circuit_info, circuit_path)
                push!(saved_files, circuit_path)
                
                # Display circuit statistics
                println("     📊 $(circuit_info.n_parameters) parameters, $(circuit_info.method_type) type")
            else
                @warn "Failed to create plot for $method_name"
            end
            
            # Create detailed text analysis
            info_filename = "$(method_name)_analysis.txt"
            info_path = joinpath(output_dir, info_filename)
            create_circuit_analysis_file(circuit_info, info_path)
            push!(saved_files, info_path)
            
        else
            @warn "Could not extract circuit for $method_name"
        end
    end
    
    # Create summary and comparison files
    if !isempty(circuit_infos)
        summary_files = create_analysis_summary(circuit_infos, molecule_name, output_dir)
        append!(saved_files, summary_files)
    end
    
    # Print final summary
    println("\n📊 Circuit Visualization Summary:")
    println("   ✅ Successfully processed: $(length(circuit_infos))/$(length(vqe_methods)) methods")
    println("   📁 Total files created: $(length(saved_files))")
    
    if !isempty(saved_files)
        println("\n📄 Generated Files:")
        for file in saved_files
            println("     • $(basename(file))")
        end
    end
    
    return saved_files
end

