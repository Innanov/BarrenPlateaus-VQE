"""
    analyze_circuit_architectures(analyzer)

Analyze circuit architectures and return a CircuitCollection.
"""
function analyze_circuit_architectures(analyzer)
    circuits = CircuitAnalysis[]
    
    # Get system info
    n_qubits = analyzer.molecular_system.n_qubits
    molecule_name = analyzer.molecular_system.name
    
    # VQE methods to analyze
    vqe_methods = ["StandardVQE", "SEAVQE", "LocalGlobalVQE", "AdiabaticVQE", "PretrainedVQE"]
    
    for method_name in vqe_methods
        try
            # Extract circuit info
            circuit_info = extract_circuit_from_vqe_method(method_name, n_qubits)
            
            if circuit_info !== nothing
                # Analyze circuit structure
                depth = estimate_circuit_depth(circuit_info.ansatz)
                gate_count = analyze_gate_structure(circuit_info.ansatz)
                complexity = calculate_complexity_score(circuit_info, depth, gate_count)
                
                analysis = CircuitAnalysis(
                    circuit_info.name,
                    circuit_info.method_type,
                    circuit_info.n_qubits,
                    circuit_info.n_parameters,
                    depth,
                    gate_count,
                    complexity
                )
                
                push!(circuits, analysis)
            else
                # Create failed entry
                failed_analysis = CircuitAnalysis(
                    method_name,
                    "Failed",
                    n_qubits,
                    0,
                    0,
                    Dict{String, Int}(),
                    0.0
                )
                push!(circuits, failed_analysis)
            end
            
        catch e
            @warn "Failed to analyze $method_name: $e"
            # Create failed entry
            failed_analysis = CircuitAnalysis(
                method_name,
                "Failed",
                n_qubits,
                0,
                0,
                Dict{String, Int}(),
                0.0
            )
            push!(circuits, failed_analysis)
        end
    end
    
    return CircuitCollection(circuits, molecule_name, n_qubits)
end

"""
    calculate_complexity_score(circuit_info::CircuitInfo, depth::Int, gate_count::Dict{String, Int})

Calculate a complexity score for the circuit.
"""
function calculate_complexity_score(circuit_info::CircuitInfo, depth::Int, gate_count::Dict{String, Int})
    try
        total_gates = sum(values(gate_count))
        gate_diversity = length(gate_count)
        param_density = circuit_info.n_parameters / circuit_info.n_qubits
        
        # Weighted complexity score
        complexity = 0.3 * param_density + 0.3 * (total_gates / circuit_info.n_qubits) + 
                    0.2 * (depth / circuit_info.n_qubits) + 0.2 * (gate_diversity / 10)
        
        return complexity
    catch
        return 0.0
    end
end

