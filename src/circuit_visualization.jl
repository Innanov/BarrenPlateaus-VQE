"""
    estimate_circuit_depth(ansatz)

Estimate the depth of a quantum circuit.
"""
function estimate_circuit_depth(ansatz)
    try
        if hasproperty(ansatz, :blocks) && isa(getproperty(ansatz, :blocks), Vector)
            return length(getproperty(ansatz, :blocks))
        else
            return 1
        end
    catch
        return 1
    end
end

"""
    analyze_gate_structure(ansatz)

Analyze the gate structure of a quantum circuit.
"""
function analyze_gate_structure(ansatz)
    gate_count = Dict{String, Int}()
    try
        count_gates_recursive!(ansatz, gate_count)
    catch e
        @warn "Gate analysis failed: $e"
    end
    return gate_count
end

"""
    count_gates_recursive!(block, gate_count::Dict{String, Int})

Recursively count gates in a circuit.
"""
function count_gates_recursive!(block, gate_count::Dict{String, Int})
    if block === nothing
        return
    end
    
    try
        block_type = typeof(block)
        type_name = string(block_type)
        
        if contains(type_name, "Chain") && hasproperty(block, :blocks)
            for sub_block in getproperty(block, :blocks)
                count_gates_recursive!(sub_block, gate_count)
            end
        elseif contains(type_name, "Put")
            if hasproperty(block, :content)
                content = getproperty(block, :content)
                gate_name = identify_gate_type(content)
                gate_count[gate_name] = get(gate_count, gate_name, 0) + 1
            else
                gate_count["Put"] = get(gate_count, "Put", 0) + 1
            end
        elseif contains(type_name, "Control")
            gate_count["CNOT"] = get(gate_count, "CNOT", 0) + 1
        else
            simplified_name = replace(type_name, r".*\." => "")
            gate_count[simplified_name] = get(gate_count, simplified_name, 0) + 1
        end
    catch e
        @warn "Gate counting failed: $e"
    end
end

"""
    identify_gate_type(gate)

Identify the type of a quantum gate.
"""
function identify_gate_type(gate)
    try
        gate_type = typeof(gate)
        type_name = string(gate_type)
        
        if contains(type_name, "Ry")
            return "Ry"
        elseif contains(type_name, "Rz")
            return "Rz"
        elseif contains(type_name, "Rx")
            return "Rx"
        elseif contains(type_name, "X")
            return "X"
        elseif contains(type_name, "Y")
            return "Y"
        elseif contains(type_name, "Z")
            return "Z"
        elseif contains(type_name, "H")
            return "H"
        else
            return replace(type_name, r".*\." => "")
        end
    catch
        return "Unknown"
    end
end

