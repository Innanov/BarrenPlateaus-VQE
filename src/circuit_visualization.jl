            write(f, svg_content)
        end
        
        println("  ✅ Created enhanced diagram: $(basename(svg_path))")
        return true
        
    catch e
        @warn "Failed to create enhanced diagram: $e"
        return create_fallback_circuit_diagram(circuit_info, save_path)
    end
end

"""
    add_circuit_metadata_to_svg(svg_content::String, circuit_info::CircuitInfo)

Add title and metadata to SVG content.
"""
function add_circuit_metadata_to_svg(svg_content::String, circuit_info::CircuitInfo)
    try
        # Create title and subtitle
        title = "$(replace(circuit_info.name, "_" => " ")) Ansatz Circuit"
        subtitle = "$(circuit_info.n_qubits) qubits • $(circuit_info.n_parameters) parameters • $(circuit_info.method_type)"
        
        # Find SVG dimensions
        width_match = match(r"width=\"([^\"]*)\""i, svg_content)
        height_match = match(r"height=\"([^\"]*)\""i, svg_content)
        
        if width_match !== nothing && height_match !== nothing
            width = try
                parse(Float64, width_match.captures[1])
            catch
                400.0
            end
            height = try
                parse(Float64, height_match.captures[1])
            catch
                300.0
            end
            
            # Create title elements
            title_elements = """
            <!-- Circuit Title and Metadata -->
            <style>
                .circuit-title { 
                    font-family: "Arial", sans-serif; 
                    font-size: 14px; 
                    font-weight: bold; 
                    text-anchor: middle; 
                    fill: #2c3e50;
                }
                .circuit-subtitle { 
                    font-family: "Arial", sans-serif; 
                    font-size: 11px; 
                    text-anchor: middle; 
                    fill: #7f8c8d;
                }
                .circuit-description {
                    font-family: "Arial", sans-serif; 
                    font-size: 9px; 
                    text-anchor: middle; 
                    fill: #95a5a6;
                }
            </style>
            <text x="$(width/2)" y="20" class="circuit-title">$title</text>
            <text x="$(width/2)" y="35" class="circuit-subtitle">$subtitle</text>
            <text x="$(width/2)" y="48" class="circuit-description">$(circuit_info.description)</text>
            <g transform="translate(0, 60)">
            """
            
            # Insert title after opening SVG tag and wrap content
            svg_with_title = replace(svg_content, 
                r"(<svg[^>]*>)" => s"\1$title_elements"
            )
            
            # Close the transform group before closing SVG
            svg_with_title = replace(svg_with_title, 
                "</svg>" => "</g></svg>"
            )
            
            # Update height to accommodate title
            svg_with_title = replace(svg_with_title, 
                r"height=\"([^\"]*)\""i => "height=\"$(height + 70)\""
            )
            
            return svg_with_title
        else
            # Fallback: just add a comment
            comment = "<!-- $title: $subtitle -->"
            return replace(svg_content, r"(<svg[^>]*>)" => s"\1$comment")
        end
        
    catch e
        @warn "Failed to add title to SVG: $e"
        return svg_content
    end
end

