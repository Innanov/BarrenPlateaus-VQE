    <rect x="50" y="90" width="800" height="300" fill="white" stroke="#bdc3c7" stroke-width="2" rx="10"/>
    <rect x="50" y="90" width="800" height="300" fill="url(#gridPattern)" opacity="0.3"/>
    
    <!-- Qubit lines -->"""
        
        # Add qubit lines and basic gate representation
        for i in 1:circuit_info.n_qubits
            y_pos = 120 + (i-1) * (280 / max(circuit_info.n_qubits, 1))
            svg_content *= """
    <line x1="80" y1="$y_pos" x2="820" y2="$y_pos" class="qubit-line"/>
    <text x="70" y="$(y_pos + 5)" class="structure">q$i</text>"""
        end
        
        # Add symbolic gate representation
        gate_x_positions = [150, 250, 350, 450, 550, 650, 750]
        gate_index = 1
        
        for (gate_type, count) in gate_analysis
            if gate_index <= length(gate_x_positions)
                x_pos = gate_x_positions[gate_index]
                for i in 1:min(circuit_info.n_qubits, 3)  # Show on first few qubits
                    y_pos = 120 + (i-1) * (280 / max(circuit_info.n_qubits, 1))
                    svg_content *= """
    <rect x="$(x_pos-15)" y="$(y_pos-10)" width="30" height="20" class="gate-box" rx="3"/>
    <text x="$x_pos" y="$(y_pos + 3)" class="gate-text">$gate_type</text>"""
                end
                gate_index += 1
            end
        end
        
        svg_content *= """
    
    <!-- Warning message -->
    <text x="450" y="420" class="warning">⚠ YaoPlots visualization failed - showing circuit structure analysis</text>
    
    <!-- Structure analysis -->
    <text x="450" y="440" class="info">$gate_summary</text>
