"""
    create_circuit_plot(circuit_info::CircuitInfo, save_path::String)

Create a YaoPlots circuit visualization and save it.
"""
function create_circuit_plot(circuit_info::CircuitInfo, save_path::String)
    if !YAOPLOTS_AVAILABLE
        @warn "YaoPlots not available, cannot create circuit plot"
        return create_fallback_circuit_diagram(circuit_info, save_path)
    end
    
    if circuit_info.ansatz === nothing
        @warn "No ansatz available for $(circuit_info.name)"
        return create_fallback_circuit_diagram(circuit_info, save_path)
    end
    
    try
        println("🎨 Creating circuit plot for $(circuit_info.name)...")
        
        # Ensure save path has .svg extension
        svg_path = endswith(save_path, ".svg") ? save_path : replace(save_path, r"\.[^.]*$" => ".svg")
        
        # Try multiple YaoPlots approaches
        success = false
        
        # Method 1: Basic vizcircuit with minimal parameters
        try
            YaoPlots.vizcircuit(circuit_info.ansatz; format=:svg, filename=svg_path)
            if isfile(svg_path)
                success = true
            end
        catch e1
            @warn "Basic vizcircuit failed: $e1"
        end
        
        # Method 2: Try without filename parameter (save manually)
        if !success
            try
                # Create drawing without filename
                drawing = YaoPlots.vizcircuit(circuit_info.ansatz; format=:svg)
                
                # Try to save using different methods
                if hasproperty(drawing, :stream) && !isempty(drawing.stream)
                    open(svg_path, "w") do f
                        write(f, String(drawing.stream))
                    end
                    success = isfile(svg_path)
                end
            catch e2
                @warn "Manual save method failed: $e2"
            end
        end
        
        # Method 3: Try basic plot function
        if !success
            try
                drawing = YaoPlots.plot(circuit_info.ansatz)
                # This might create a display that we can't easily save
                # but let's try to extract content
                success = false  # We'll handle this in fallback
            catch e3
                @warn "Plot method failed: $e3"
            end
        end
        
        # Check if we succeeded
        if success && isfile(svg_path)
            # Add enhanced metadata to the saved SVG
            enhance_saved_svg_metadata(svg_path, circuit_info)
            println("  ✅ Saved: $(basename(svg_path))")
            return true
        else
            @warn "All YaoPlots methods failed for $(circuit_info.name), using enhanced fallback"
            return create_enhanced_circuit_diagram(circuit_info, save_path)
        end
        
    catch e
        @warn "Failed to create circuit plot for $(circuit_info.name): $e"
        # Try fallback method
        return create_enhanced_circuit_diagram(circuit_info, save_path)
    end
end

"""
    enhance_saved_svg_metadata(svg_path::String, circuit_info::CircuitInfo)

Add enhanced metadata to an already saved SVG file.
"""
function enhance_saved_svg_metadata(svg_path::String, circuit_info::CircuitInfo)
    try
        # Read the existing SVG file
        svg_content = read(svg_path, String)
        
        # Add metadata as SVG comments
        metadata_comment = """
<!-- Circuit Metadata -->
<!-- Method: $(circuit_info.name) -->
<!-- Type: $(circuit_info.method_type) -->
<!-- Qubits: $(circuit_info.n_qubits) -->
<!-- Parameters: $(circuit_info.n_parameters) -->
<!-- Description: $(circuit_info.description) -->
<!-- Generated: $(Dates.now()) -->
<!-- BarrenPlateausVQE.jl Circuit Visualization -->
"""
        
        # Insert metadata after the opening SVG tag
        enhanced_svg = replace(svg_content, 
            r"(<svg[^>]*>)" => s"\1$metadata_comment"
        )
        
        # Write back the enhanced SVG
        open(svg_path, "w") do f
            write(f, enhanced_svg)
        end
        
    catch e
        @warn "Failed to enhance SVG metadata: $e"
    end
end

"""
    create_enhanced_circuit_diagram(circuit_info::CircuitInfo, save_path::String)

Create an enhanced circuit diagram with actual circuit structure analysis.
"""
