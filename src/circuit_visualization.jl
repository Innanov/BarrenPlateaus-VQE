"""
    extract_circuit_from_vqe_method(method_name::String, n_qubits::Int)

Create a VQE method instance and extract its ansatz circuit.
"""
function extract_circuit_from_vqe_method(method_name::String, n_qubits::Int)
    try
        # Access VQE methods from the parent BarrenPlateausVQE module
        parent = parentmodule(@__MODULE__)
        
        if method_name == "StandardVQE"
            StandardVQE = getfield(parent, :StandardVQE)
            vqe = StandardVQE(n_qubits, 1)  # 1 layer
            return CircuitInfo(
                "StandardVQE",
                vqe.ansatz,
                vqe.n_qubits,
                vqe.n_parameters,
                "Hardware-Efficient",
                "Standard VQE with EfficientSU2 ansatz using Ry and Rz rotations"
            )
            
        elseif method_name == "SEAVQE"
            SEAVQE = getfield(parent, :SEAVQE)
            vqe = SEAVQE(n_qubits)
            return CircuitInfo(
                "SEAVQE",
                vqe.ansatz,
                vqe.n_qubits,
                vqe.n_parameters,
                "State-Efficient",
                "State Efficient Ansatz with 3-layer structure for barren plateau mitigation"
            )
            
        elseif method_name == "LocalGlobalVQE"
            LocalGlobalVQE = getfield(parent, :LocalGlobalVQE)
            vqe = LocalGlobalVQE(n_qubits, 1)  # 1 layer
            return CircuitInfo(
                "LocalGlobalVQE",
                vqe.ansatz,
                vqe.n_qubits,
                vqe.n_parameters,
                "Local-Global",
                "Local-Global VQE using same ansatz as StandardVQE but two-stage optimization"
            )
            
        elseif method_name == "AdiabaticVQE"
            AdiabaticVQE = getfield(parent, :AdiabaticVQE)
            vqe = AdiabaticVQE(n_qubits, 1)  # 1 layer
            return CircuitInfo(
                "AdiabaticVQE",
                vqe.ansatz,
                vqe.n_qubits,
                vqe.n_parameters,
                "Adiabatic",
                "Adiabatic VQE with gradual Hamiltonian interpolation"
            )
            
        elseif method_name == "PretrainedVQE"
            PretrainedVQE = getfield(parent, :PretrainedVQE)
            vqe = PretrainedVQE(n_qubits)
            # Use the full ansatz for visualization
            return CircuitInfo(
                "PretrainedVQE",
                vqe.full_ansatz,
                vqe.n_qubits,
                vqe.full_n_parameters,
                "MPS-Enhanced",
                "Pretrained VQE with MPS parameter initialization and full ansatz"
            )
            
        else
            throw(ArgumentError("Unknown VQE method: $method_name"))
        end
        
    catch e
        @warn "Failed to create $method_name: $e"
        return nothing
    end
end

"""
    extract_circuit_from_analyzer_results(method_name::String, data::Dict)

Extract circuit info from analyzer results (fallback method).
"""
function extract_circuit_from_analyzer_results(method_name::String, data::Dict)
    try
        method_result = data["method_result"]
        
        # Check if method failed
        if get(method_result, "fallback", false)
            return nothing
        end
        
        # Extract based on method structure
        ansatz = nothing
        n_qubits = 0
        n_parameters = 0
        
        if method_name == "PretrainedVQE" && haskey(method_result, "full")
            ansatz_info = method_result["full"]["ansatz_info"]
            ansatz = ansatz_info["ansatz"]
            n_qubits = ansatz_info["n_qubits"]
            n_parameters = ansatz_info["n_parameters"]
        elseif method_name == "LocalGlobalVQE" && haskey(method_result, "out")
            ansatz_info = method_result["out"]["ansatz_info"]
            ansatz = ansatz_info["ansatz"]
            n_qubits = ansatz_info["n_qubits"]
            n_parameters = ansatz_info["n_parameters"]
        elseif haskey(method_result, "ansatz_info")
            ansatz_info = method_result["ansatz_info"]
            ansatz = ansatz_info["ansatz"]
            n_qubits = ansatz_info["n_qubits"]
            n_parameters = ansatz_info["n_parameters"]
        else
            return nothing
        end
        
        if ansatz === nothing || n_qubits <= 0
            return nothing
        end
        
        # Classify method type
        method_type = if contains(lowercase(method_name), "standard")
            "Hardware-Efficient"
        elseif contains(lowercase(method_name), "sea")
            "State-Efficient"
        elseif contains(lowercase(method_name), "local")
            "Local-Global"
        elseif contains(lowercase(method_name), "adiabatic")
            "Adiabatic"
        elseif contains(lowercase(method_name), "pretrained")
            "MPS-Enhanced"
        else
            "Custom"
        end
        
        return CircuitInfo(
            method_name,
            ansatz,
            n_qubits,
            n_parameters,
            method_type,
            "Extracted from analyzer results"
        )
        
    catch e
        @warn "Failed to extract circuit from analyzer results for $method_name: $e"
        return nothing
    end
end

