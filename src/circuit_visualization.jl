        svg_path = endswith(save_path, ".svg") ? save_path : replace(save_path, r"\.[^.]*$" => ".svg")
        
        # Analyze the actual circuit structure
        gate_analysis = analyze_gate_structure(circuit_info.ansatz)
        depth = estimate_circuit_depth(circuit_info.ansatz)
        
        # Create a more detailed circuit representation
        gate_summary = if !isempty(gate_analysis)
            total_gates = sum(values(gate_analysis))
            gate_types = collect(keys(gate_analysis))
            gate_counts = collect(values(gate_analysis))
            "Gates: " * join(["$gate ($count)" for (gate, count) in zip(gate_types, gate_counts)], ", ")
        else
            "Circuit structure analysis unavailable"
        end
        
        # Create enhanced SVG with actual circuit information
        svg_content = """<?xml version="1.0" encoding="UTF-8"?>
<svg width="900" height="500" xmlns="http://www.w3.org/2000/svg">
    <defs>
        <linearGradient id="bgGradient" x1="0%" y1="0%" x2="100%" y2="100%">
            <stop offset="0%" style="stop-color:#f8f9fa;stop-opacity:1" />
            <stop offset="100%" style="stop-color:#e9ecef;stop-opacity:1" />
        </linearGradient>
        <pattern id="gridPattern" width="20" height="20" patternUnits="userSpaceOnUse">
            <path d="M 20 0 L 0 0 0 20" fill="none" stroke="#dee2e6" stroke-width="0.5"/>
        </pattern>
    </defs>
    
    <style>
        .title { font-family: "Arial", sans-serif; font-size: 18px; font-weight: bold; text-anchor: middle; fill: #2c3e50; }
        .subtitle { font-family: "Arial", sans-serif; font-size: 14px; text-anchor: middle; fill: #34495e; }
        .info { font-family: "Arial", sans-serif; font-size: 12px; text-anchor: middle; fill: #7f8c8d; }
        .warning { font-family: "Arial", sans-serif; font-size: 11px; text-anchor: middle; fill: #e74c3c; }
        .structure { font-family: "Courier New", monospace; font-size: 10px; text-anchor: start; fill: #2c3e50; }
        .qubit-line { stroke: #34495e; stroke-width: 2; }
        .gate-box { fill: #3498db; stroke: #2980b9; stroke-width: 2; }
        .gate-text { font-family: "Arial", sans-serif; font-size: 10px; text-anchor: middle; fill: white; font-weight: bold; }
    </style>
    
    <!-- Background -->
    <rect width="900" height="500" fill="url(#bgGradient)"/>
    
    <!-- Header -->
    <text x="450" y="30" class="title">$(circuit_info.name) Circuit Architecture</text>
    <text x="450" y="50" class="subtitle">$(circuit_info.method_type) Ansatz</text>
    <text x="450" y="70" class="info">$(circuit_info.n_qubits) qubits • $(circuit_info.n_parameters) parameters • Depth: $depth</text>
    
